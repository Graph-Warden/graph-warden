import { describe, expect, it } from "vitest";
import {
  createAsker,
  createEraser,
  createRevalidator,
  createRouter,
  createSensitivityPolicy,
  createWriter,
  routeModels,
  Unroutable,
  type Edge,
  type LLMProvider,
  type LLMRequest,
  type Node,
  type StaleMarks,
} from "../src/index.js";
import { memoryAudit, memoryEvents, memoryStore } from "./memory.js";

// Issue #28: no content of a confidential source is ever sent to the remote provider.

const SECRET = "Lea's salary is 81 000 euros";
const CODE_SECRET = "PAYROLL_SIGNING_KEY rotation";
const policy = createSensitivityPolicy({ confidential: ["docs:hr", "github:acme/payroll*"] });

const node = (id: string, type: string, source: string, body: string): Node => ({
  id,
  type,
  scope: { kind: "shared" },
  provenance: { source, path: `${id}.md` },
  title: id,
  body,
});

const nodes: Node[] = [
  node("hr-salaries", "Concept", "docs:hr", `${SECRET}. Salary reviews happen in March.`),
  node("wiki-salaries", "Concept", "docs:wiki", "Salary reviews are announced on the wiki."),
  node("wiki-pay", "Decision", "docs:wiki", "Pay slips are generated by the payroll service."),
  node("payroll", "Module", "github:acme/payroll", "export function sign() {}"),
  node("shop", "Module", "github:acme/shop", "export function cart() {}"),
  node("hr-shop", "Decision", "docs:hr", `${SECRET}; the shop gives staff a discount.`),
  node("report", "Concept", "ask:lea", `Reviews in March; ${SECRET}.`),
  node("payroll@abc", "Change", "github:acme/payroll", "rotate keys"),
  node("shop@def", "Change", "github:acme/shop", "cart"),
];
const edges: Edge[] = [
  { type: "DECIDES", from: "wiki-pay", to: "payroll" },
  { type: "DECIDES", from: "hr-shop", to: "shop" },
  { type: "DERIVED_FROM", from: "report", to: "hr-salaries" },
  { type: "DERIVED_FROM", from: "report", to: "wiki-salaries" },
];

// A model recording every request it was sent.
function spy(answer = '{"verdict": "valid", "reason": "Still true."}'): LLMProvider & { readonly sent: LLMRequest[] } {
  const sent: LLMRequest[] = [];
  return { sent, complete: async (request) => (sent.push(request), answer) };
}

const noMarks: StaleMarks = { mark: async () => {}, get: async () => undefined, clear: async () => {}, clearSource: async () => {} };
const lea = { user: "lea", teams: ["hr"] };

async function setup(local?: LLMProvider) {
  const store = memoryStore();
  const writer = createWriter(store, memoryEvents());
  await writer.upsertNodes(nodes);
  await writer.upsertEdges(edges);
  const audit = memoryAudit();
  const remote = spy();
  const llm = createRouter({ remote, ...(local === undefined ? {} : { local }), policy, audit });
  return { store, writer, audit, remote, llm };
}

const leaks = (requests: readonly LLMRequest[]) =>
  requests.filter((request) => [SECRET, CODE_SECRET].some((secret) => `${request.system}\n${request.prompt}`.includes(secret)));

describe("routing by sensitivity", () => {
  it("never sends confidential content to the remote model, from ask, revalidation or erasure", async () => {
    const local = spy();
    const { store, writer, audit, remote, llm } = await setup(local);

    // ask: the HR document is retrieved with the wiki one.
    const asker = createAsker(store, writer, audit, llm);
    await asker.ask(lea, "When are salary reviews?");
    // Anchored on the wiki decision, it reads the payroll module too: confidential.
    await asker.ask(lea, "Who generates pay slips?", { from: "wiki-pay" });
    await asker.ask(lea, "Where is it announced?");

    // revalidation: a change of the confidential repository, with its diff, and a change of a
    // shared one that a confidential decision depends on.
    const revalidator = createRevalidator({ store, writer, llm, marks: noMarks });
    await revalidator.revalidate({ change: "github:acme/payroll@abc", changed: ["payroll"], evidence: `sign.ts: ${CODE_SECRET}`, author: lea });
    await revalidator.revalidate({ change: "github:acme/shop@def", changed: ["shop"], evidence: "cart.ts: free shipping", author: lea });

    // erasure: the report keeps the HR document when the wiki one goes.
    const eraser = createEraser(store, writer, audit, { llm: { complete: async (request) => (await llm.complete(request), "Reviews in March.") } });
    await eraser.forget(lea, "docs:wiki", (await eraser.plan(lea, "docs:wiki")).digest);

    expect(leaks(remote.sent)).toEqual([]);
    // Everything that held confidential content was handled, locally.
    expect(leaks(local.sent).length).toBeGreaterThanOrEqual(4);
    // The remote model did get what is not confidential.
    expect(remote.sent.some((request) => request.prompt.includes("announced on the wiki"))).toBe(true);

    const routes = audit.written.filter((entry) => entry.action === "route");
    expect(routes).toHaveLength(remote.sent.length + local.sent.length);
    expect(routes.filter((entry) => entry.model === "local").every((entry) => entry.confidential.length > 0)).toBe(true);
    expect(routes.find((entry) => entry.model === "remote")).toMatchObject({ principal: lea, sources: ["docs:wiki"], confidential: [] });
  });

  describe("a node derived from a confidential source", () => {
    const derived = (id: string, source: string, body: string, from: string): { node: Node; edge: Edge } => ({ node: node(id, "Concept", source, body), edge: { type: "DERIVED_FROM", from: id, to: from } });

    async function withDerived() {
      const ready = await setup();
      const first = derived("bonus-answer", "ask:lea", `Bonus figures: ${SECRET}.`, "hr-salaries");
      const second = derived("bonus-digest", "ask:lea", `Quarterly digest: ${SECRET}.`, "bonus-answer");
      await ready.writer.upsertNodes([first.node, second.node]);
      await ready.writer.upsertEdges([first.edge, second.edge]);
      return ready;
    }

    it("stays away from the remote model when `ask` finds it by its own words", async () => {
      const { store, writer, audit, remote, llm } = await withDerived();
      await expect(createAsker(store, writer, audit, llm).ask(lea, "bonus figures")).rejects.toThrow(Unroutable);
      expect(leaks(remote.sent)).toEqual([]);
    });

    it("stays away from it however many derivations it took", async () => {
      const { store, writer, audit, remote, llm } = await withDerived();
      await expect(createAsker(store, writer, audit, llm).ask(lea, "quarterly digest")).rejects.toThrow(Unroutable);
      expect(leaks(remote.sent)).toEqual([]);
    });

    const refused = (audit: ReturnType<typeof memoryAudit>) => audit.written.filter((entry) => entry.action === "route" && entry.denied === true && entry.confidential.includes("docs:hr"));

    it("stays away from it when it is revalidated", async () => {
      const { store, writer, audit, remote, llm } = await withDerived();
      await writer.upsertNodes([node("bonus-code", "Module", "github:acme/bonus", "export function bonus() {}")]);
      await writer.upsertEdges([{ type: "DERIVED_FROM", from: "bonus-answer", to: "bonus-code" }]);
      await createRevalidator({ store, writer, llm, marks: noMarks }).revalidate({ change: "github:acme/bonus@abc", changed: ["bonus-code"], evidence: "bonus.ts: renamed", author: lea }).catch(() => undefined);
      expect(refused(audit).length).toBeGreaterThan(0);
      expect(leaks(remote.sent)).toEqual([]);
    });

    it("stays away from it when a node is recompiled from it", async () => {
      const { store, writer, audit, remote, llm } = await withDerived();
      await writer.upsertNodes([node("wiki-note", "Concept", "docs:notes", "Note."), node("summary", "Concept", "docs:wiki", "Summary.")]);
      await writer.upsertEdges([{ type: "DERIVED_FROM", from: "summary", to: "wiki-note" }, { type: "DERIVED_FROM", from: "summary", to: "bonus-answer" }]);
      const eraser = createEraser(store, writer, audit, { llm });
      await expect(eraser.forget(lea, "docs:notes", (await eraser.plan(lea, "docs:notes")).digest)).rejects.toThrow(Unroutable);
      expect(refused(audit).length).toBeGreaterThan(0);
      expect(leaks(remote.sent)).toEqual([]);
    });
  });

  it("keeps a confidential node out when only a link would bring it, so that a link never changes where a question goes", async () => {
    const { store, writer, audit, llm, remote } = await setup();
    await createAsker(store, writer, audit, llm).ask(lea, "Where is it announced?");
    expect(leaks(remote.sent)).toEqual([]);
    expect(remote.sent).toHaveLength(1);
  });

  it("follows links to anything when every question stays local anyway", async () => {
    const local = spy();
    const llm = createRouter({ local, policy: createSensitivityPolicy({ default: "confidential" }), audit: memoryAudit() });
    expect(llm.narrows?.("docs:hr")).toBe(false);
  });

  it("refuses confidential content when there is no local model, and audits the refusal", async () => {
    const { store, writer, audit, remote, llm } = await setup();
    const asker = createAsker(store, writer, audit, llm);
    await expect(asker.ask(lea, "When are salary reviews?")).rejects.toThrow(Unroutable);
    expect(remote.sent).toEqual([]);
    expect(audit.written.find((entry) => entry.action === "route")).toMatchObject({ model: "local", denied: true, confidential: ["docs:hr"] });
  });

  it("keeps a request that names no sources local", async () => {
    const local = spy("ok");
    const { remote, llm } = await setup(local);
    await llm.complete({ system: "s", prompt: SECRET });
    expect(remote.sent).toEqual([]);
    expect(local.sent).toHaveLength(1);
  });

  it("is left out when neither a local model nor a policy is configured", async () => {
    const remote = spy();
    const audit = memoryAudit();
    expect(routeModels({ remote, local: undefined, audit })).toBe(remote);
    // A local model alone takes everything.
    const local = spy("ok");
    await routeModels({ remote, local, audit })?.complete({ system: "s", prompt: "p", sources: ["docs:wiki"] });
    expect(local.sent).toHaveLength(1);
    expect(remote.sent).toEqual([]);
  });
});

describe("createSensitivityPolicy", () => {
  it("matches sources exactly or by prefix, confidential first, then the default", () => {
    expect(policy.of("docs:hr")).toBe("confidential");
    expect(policy.of("docs:hr-archive")).toBe("internal");
    expect(policy.of("github:acme/payroll-infra")).toBe("confidential");
    expect(policy.of("docs:wiki")).toBe("internal");
    const strict = createSensitivityPolicy({ default: "confidential", internal: ["docs:wiki", "docs:*"], confidential: ["docs:hr"] });
    expect(strict.of("docs:wiki")).toBe("internal");
    expect(strict.of("docs:hr")).toBe("confidential");
    expect(strict.of("github:acme/shop")).toBe("confidential");
    expect(() => createSensitivityPolicy({ secret: [] } as never)).toThrow();
  });
});
